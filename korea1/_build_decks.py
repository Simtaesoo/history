def split_videos(body):
    """영상(V)이 다른 내용과 한 장에 있으면, 영상을 바로 앞의 '영상' 슬라이드로 떼어 낸다(TV에서 크게 보이게)."""
    out, cur = [], []
    def flush():
        if not cur: return
        head, rest = cur[0], cur[1:]
        vids = [l for l in rest if l.startswith("V ")]
        other = [l for l in rest if l.strip() and not l.startswith(("V ", "% ", "||"))]
        if head.startswith("= ") and vids and other:
            title = head[2:].split("|")[0].strip()
            out.append(f"= {title} | 영상으로 보기")
            out.extend(vids)
            out.append("")
            out.append(head)
            out.extend(l for l in rest if not l.startswith(("V ", "||")))
        else:
            out.extend(cur)
        cur.clear()
    for line in body.split("\n"):
        if line.startswith(("= ", "## ", "# ")):
            flush()
        cur.append(line)
    flush()
    return "\n".join(out)

